"""Lookup tables of the PHYS engine's Rings models (src/rings_dsp.c), in fixed point.

The curves are those of rings/resources/lookup_tables.py (Emilie Gillet, MIT; pichenettes/eurorack): the
resonator's stiffness against STRUCTURE, the decades table behind its Q, the delay compensation of the string's
low-pass, and the FM voice's ratio quantizer. Written as C arrays (build/gen/rings_tables.h).

  RG_STIFF[257]   stiffness of STRUCTURE i / 256, Q16 (signed; the last two entries are 2.0)
  RG_DEC4[257]    10^(4 i / 256), Q16 (1 .. 10000)
  RG_SVFSHIFT[257] 2 atan(2^(-i / 12)) / 2 pi, Q30: how much delay the low-pass adds at i semitones above the string
  RG_FMQ[129]     the quantised FM ratios as semitones, Q16 (the table lut_fm_frequency_quantizer: 128 + 1 points)
"""
import math
import sys


def arr(name, ctype, vals, per=8):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def stiffness():
    s = []
    for i in range(257):
        g = i / 256.0
        if g < 0.25:
            v = -(0.25 - g) * 0.25
        elif g < 0.3:
            v = 0.0
        elif g < 0.9:
            v = 0.01 * 10 ** ((g - 0.3) / 0.6 * 2.005) - 0.01
        else:
            g = (g - 0.9) / 0.1
            g *= g
            v = 1.5 - math.cos(g * math.pi) / 2.0
        s.append(v)
    s[-1] = 2.0
    s[-2] = 2.0
    return s


def fm_quantizer():
    ratios = [0.5, 0.5 * 2 ** (16 / 1200.0), math.sqrt(2) / 2, math.pi / 4, 1.0, 1.0 * 2 ** (16 / 1200.0),
              math.sqrt(2), math.pi / 2, 7.0 / 4, 2, 2 * 2 ** (16 / 1200.0), 9.0 / 4, 11.0 / 4, 2 * math.sqrt(2), 3,
              math.pi, math.sqrt(3) * 2, 4, math.sqrt(2) * 3, math.pi * 3 / 2, 5, math.sqrt(2) * 4, 8]
    scale = []
    for r in ratios:
        r = 12 * math.log2(r)
        scale += [r, r, r]
    target = 1 << math.ceil(math.log2(len(scale)))
    while len(scale) < target:                 # fill the widest gaps with their midpoints (as the original script)
        gap = max(range(len(scale) - 1), key=lambda k: scale[k + 1] - scale[k])
        scale = scale[:gap + 1] + [(scale[gap] + scale[gap + 1]) / 2] + scale[gap + 1:]
    scale.append(scale[-1])
    return scale


def main(path):
    L = ["/* generated by tools/gen_rings_tables.py */", "#pragma once", "#include <stdint.h>", ""]
    L += arr("RG_STIFF", "int32_t", [int(round(v * 65536)) for v in stiffness()])
    L += arr("RG_DEC4", "int32_t", [int(round(10 ** (4 * i / 256.0) * 65536)) for i in range(257)])
    L += arr("RG_SVFSHIFT", "int32_t",
             [int(round(2.0 * math.atan(1.0 / 2.0 ** (i / 12.0)) / (2 * math.pi) * (1 << 30))) for i in range(257)])
    fmq = fm_quantizer()
    assert len(fmq) == 129, len(fmq)
    L += arr("RG_FMQ", "int32_t", [int(round(v * 65536)) for v in fmq])
    text = "\n".join(L) + "\n"
    with open(path, "w") as f:
        f.write(text)
    print(f"rings tables: {len(text)} B -> {path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "rings_tables.h")
