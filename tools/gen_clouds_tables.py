"""Lookup tables of the CLOUDS effect (src/clouds_dsp.c), in fixed point.

The curves are those of clouds/resources/lookup_tables.py and src_filters.py (Emilie Gillet, MIT;
pichenettes/eurorack) and stmlib's SoftLimit (MIT). Written as C arrays (build/gen/clouds_tables.h).

  CL_SIN[1281]      sin(2 pi i / 1024), i = 0 .. 1280 (a period and a quarter: cos = sin + 256), Q15   [lut_sin]
  CL_WIN[1025]      the grains' smooth window 1 - (cos(pi t) + 1) / 2, t = i / 1024, Q15 (lut_window, 4097 points,
                    read every fourth: linear between them)
  CL_XFI[17]        the BLEND crossfade, sin(t) / sqrt(2), Q15                                         [lut_xfade_in]
  CL_XFO[17]        .. cos(t) / sqrt(2), Q15                                                          [lut_xfade_out]
  CL_PVWIN[FFT]     the phase vocoder's window (the "power" window, overlap 4) for its FFT (2048; --fft 4096 for the
                    host test), Q15 (lut_sine_window_4096 read with the STFT's stride for that size)
  CL_GSIZE[257]     the grain size of SIZE i / 256, samples at 32 kHz: floor(1024 * 2^(4 i / 256))   [lut_grain_size]
  CL_SRC[45]        the 2:1 resampling filter (src_filter_1x_2_45: remez, 45 taps, sum 1), Q16
  CL_HB[8]          the device's outer 2:1 resampling (44.1 <-> 22.05 kHz), a 31-tap half-band: the taps at 1, 3 .. 15
                    from its 0.5 centre, Q16
  CL_ULAW[256]      the mu-law decoder (clouds/dsp/mu_law.cc lut_ulaw), Q15
  CL_ATN[257]       atan(i / 256), a 1/65536 turn; CL_HYP[257] sqrt(1 + (i / 256)^2), Q15: atan2 and the magnitude of a
                    bin from the ratio of its smaller side to its larger (Clouds: stmlib fast_atan2r)
  CL_SOFT[257]      SoftLimit(x) = x (27 + x^2) / (27 + 9 x^2) for x = -3 .. 3 in 256 steps, Q15 (stmlib dsp.h)
  CL_TWQ[FFT/4+1]   sin(pi / 2 * i / (FFT / 4)), Q30: the FFT's twiddles (a quarter wave)
"""
import math
import sys

# src_filter_1x_2_45 of clouds/resources.cc (generated by clouds/resources/src_filters.py with scipy's remez,
# which this build does not need): 45 taps, symmetric, sum 1
SRC_45 = [
    -6.928606892e-04, -5.894682972e-03, 4.393903915e-04, 5.352009980e-03,
    1.833575577e-03, -7.103853054e-03, -5.275577768e-03, 7.999060050e-03,
    1.029879712e-02, -7.191125897e-03, -1.675763381e-02, 3.628265970e-03,
    2.423749384e-02, 4.020326715e-03, -3.208822586e-02, -1.775516900e-02,
    3.947412082e-02, 4.200610725e-02, -4.553678524e-02, -9.270618476e-02,
    4.952442102e-02, 3.157869177e-01, 4.528032253e-01, 3.157869177e-01,
    4.952442102e-02, -9.270618476e-02, -4.553678524e-02, 4.200610725e-02,
    3.947412082e-02, -1.775516900e-02, -3.208822586e-02, 4.020326715e-03,
    2.423749384e-02, 3.628265970e-03, -1.675763381e-02, -7.191125897e-03,
    1.029879712e-02, 7.999060050e-03, -5.275577768e-03, -7.103853054e-03,
    1.833575577e-03, 5.352009980e-03, 4.393903915e-04, -5.894682972e-03,
    -6.928606892e-04,
]


# the outer 2:1 resampling of the device (44.1 <-> 22.05 kHz; not Clouds'): a 31-tap half-band (scipy remez, passband
# to 0.2, stopband from 0.3 of the high rate: 0.02 dB, -57 dB), its 8 taps either side of the 0.5 centre, at odd offsets
HB_31 = [3.161016914e-01, -9.854823300e-02, 5.159082168e-02, -2.981834823e-02, 1.722798282e-02, -9.434561739e-03,
         4.652803506e-03, -2.107096868e-03]


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def q(x, bits):
    return int(math.floor(x * (1 << bits) + 0.5))


def ulaw():
    """the G.711 mu-law decoder as clouds' lut_ulaw (its values, computed)"""
    out = []
    for u in range(256):
        v = ~u & 0xFF
        t = (((v & 0x0F) << 3) + 0x84) << ((v & 0x70) >> 4)
        out.append((0x84 - t) if v & 0x80 else (t - 0x84))
    return out


def pv_window(n=4096, fft=2048):
    t = [i / n for i in range(n)]
    power = [(1.0 - (2 * x - 1.0) ** 2.0) ** 1.25 for x in t]
    half = n // 2
    comp = [math.sqrt(power[i] ** 2 + power[i + half] ** 2) for i in range(half)] * 2
    w = [p / c if c else 0.0 for p, c in zip(power, comp)]
    stride = n // fft
    return [min(32768, q(w[i * stride], 15)) for i in range(fft)]


FFT = 2048


def main():
    global FFT
    args = sys.argv[1:]
    if args[:1] == ["--fft"]:                        # the host test against Clouds' 4096 points
        FFT = int(args[1])
        args = args[2:]
    lines = ["/* generated by tools/gen_clouds_tables.py: do not edit */", "#include <stdint.h>",
             f"#define CL_TABLES_FFT {FFT}"]
    lines += arr("CL_SIN", "int16_t", [max(-32767, min(32767, q(math.sin(2 * math.pi * i / 1024), 15)))
                                       for i in range(1281)])
    lines += arr("CL_WIN", "uint16_t", [q(1.0 - (math.cos(i / 1024 * math.pi) + 1) / 2, 15) for i in range(1025)])
    xi, xo = [], []
    for i in range(17):
        t = 1.04 * (i / 16) - 0.02
        t = min(1.0, max(0.0, t)) * math.pi / 2
        xi.append(q(math.sin(t) * 2 ** -0.5, 15))
        xo.append(q(math.cos(t) * 2 ** -0.5, 15))
    lines += arr("CL_XFI", "int16_t", xi)
    lines += arr("CL_XFO", "int16_t", xo)
    lines += arr("CL_PVWIN", "uint16_t", pv_window(4096, FFT))
    lines += arr("CL_GSIZE", "uint16_t", [int(math.floor(1024 * 2 ** (i / 256 * 4))) for i in range(257)])
    src = [q(c, 16) for c in SRC_45]
    src[22] += 65536 - sum(src)                          # sum exactly 1 (Q16): no gain through a pair
    lines += arr("CL_SRC", "int32_t", src)
    hb = [q(c, 16) for c in HB_31]
    hb[0] += (65536 - 32768 - 2 * sum(hb)) // 2              # 0.5 + 2 sum = 1 exactly (Q16)
    lines += arr("CL_HB", "int32_t", hb)
    lines += arr("CL_ULAW", "int16_t", ulaw())
    lines += arr("CL_ATN", "uint16_t", [q(math.atan(i / 256) / (2 * math.pi), 16) for i in range(257)])
    lines += arr("CL_HYP", "uint16_t", [q(math.sqrt(1 + (i / 256) ** 2), 15) for i in range(257)])
    soft = []
    for i in range(257):
        x = -3.0 + 6.0 * i / 256
        soft.append(q(x * (27 + x * x) / (27 + 9 * x * x), 15))
    lines += arr("CL_SOFT", "int16_t", soft)
    quarter = FFT // 4
    lines += arr("CL_TWQ", "int32_t", [min((1 << 30), q(math.sin(math.pi / 2 * i / quarter), 30))
                                       for i in range(quarter + 1)])
    size = 2 * 1281 + 2 * 1025 + 4 * 17 + 2 * FFT + 2 * 257 + 4 * 45 + 4 * 8 + 2 * 256 + 4 * 257 + 2 * 257 + 4 * (FFT // 4 + 1)
    out = args[0] if args else None
    text = "\n".join(lines) + "\n"
    if out:
        with open(out, "w") as f:
            f.write(text)
        print(f"clouds tables: {size} B -> {out}")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
